using System;
using System.Text;
using Ores.Net.Runtime;
using static Ores.Net.Runtime.BufferedStdioAdmission;
static void Check(bool b) { if (!b) throw new Exception("stdio admission assertion"); }
Owner a = new(1,1), b = new(1,2);
var q = new BufferedStdioAdmission(4,4,4,8);
Check(q.Admit(a,"123",out _) == Result.Accepted);
Check(q.TakeSink(out var s,out var first) && Encoding.UTF8.GetString(first!)=="123");
Check(q.Admit(a,"XX",out var head)==Result.Pending);
Check(q.Admit(b,"Y",out var tail)==Result.Pending);
Check(!q.Cancel(b,head) && q.Cancel(a,head));
Check(q.TakeReady(a,tail)==Result.Stale && q.TakeReady(b,tail)==Result.Accepted);
Check(q.TakeReady(b,tail)==Result.Stale && !q.Cancel(b,tail));
Check(q.AcceptedBytes==4 && q.FinishSink(s,true)==Result.Accepted);
Check(q.TakeSink(out s,out var last) && Encoding.UTF8.GetString(last!)=="Y");
Check(q.FinishSink(s,true)==Result.Accepted && q.Drained);
Console.WriteLine("PASS: FIFO, byte cap, cancellation and generation");
var x = new BufferedStdioAdmission(1,4,1,4);
var y = new BufferedStdioAdmission(1,4,1,4);
Check(x.Admit(a,"éé",out _)==Result.Accepted && y.Admit(a,"éé",out _)==Result.Accepted);
Check(x.Admit(a,"a",out var tx)==Result.Pending); Check(y.Admit(a,"b",out var ty)==Result.Pending);
Check(tx!=ty && !y.Cancel(a,tx) && y.TakeReady(a,tx)==Result.Stale);
Check(x.TakeSink(out var sx,out _)); Check(y.TakeSink(out var sy,out _));
Check(y.FinishSink(sx,true)==Result.Stale && y.FinishSink(sy,true)==Result.Accepted);
Check(y.Admit(b,"z",out _)==Result.Quota);
y.Retire(a); Check(y.TakeReady(a,ty)==Result.Stale);
Check(y.Admit(b,"z",out var next)==Result.Pending);
y.Retire(a); Check(y.TakeReady(b,next)==Result.Pending);
Check(y.TakeSink(out sy,out _) && y.FinishSink(sy,true)==Result.Accepted);
Check(y.TakeReady(b,next)==Result.Accepted);
x.Abort(); Check(x.TakeReady(a,tx)==Result.Failed && x.AcceptedBytes==4 && !x.Drained);
Check(x.FinishSink(sx,true)==Result.Failed && x.Drained && x.AcceptedBytes==0);
Console.WriteLine("PASS: cross-descriptor replay, bounded ready receipts, retirement and abort");
var z = new BufferedStdioAdmission(1,4,2,2);
Check(z.Admit(a,"😀x",out _)==Result.Oversize);
Check(z.Admit(a,new string((char)0xd800,1),out _)==Result.Invalid);
Check(z.Admit(a,"",out _)==Result.Accepted && z.AcceptedRecords==1);
Check(z.Admit(a,"yy",out var pending)==Result.Pending && z.Admit(b,"z",out _)==Result.Quota);
z.Seal(); Check(z.TakeReady(a,pending)==Result.Closed && z.Admit(b,"z",out _)==Result.Closed);
Check(z.TakeSink(out var sz,out var zero) && zero!.Length==0 && z.FinishSink(sz,true)==Result.Accepted);
Console.WriteLine("PASS: strict UTF-8, empty records, seal and quotas");
